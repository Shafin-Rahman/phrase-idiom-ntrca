export function getMnemonic(phrase: string, bnMeaning: string, enMeaning: string): string {
  const trimmed = phrase.trim();
  const direct = CURATED_MNEMONICS[trimmed];
  if (direct) return direct.mnemonic;

  const ciKey = Object.keys(CURATED_MNEMONICS).find(
    key => key.toLowerCase() === trimmed.toLowerCase(),
  );
  if (ciKey) return CURATED_MNEMONICS[ciKey].mnemonic;

  const stopWords = new Set(['a', 'an', 'the', 'to', 'in', 'of', 'on', 'at', 'by']);
  const words = trimmed.split(' ').filter(w => w.trim() && !stopWords.has(w.toLowerCase()));
  const keyword = words[0] || phrase;
  return `Memory Link: Connect the imagery of '${keyword}' directly to '${
    bnMeaning.trim() ? bnMeaning : enMeaning
  }' for instant exam recall.`;
}

export function getExamTip(
  phrase: string,
  bnMeaning: string,
  enMeaning: string,
  examName?: string | null,
): string {
  const trimmed = phrase.trim();
  const direct = CURATED_MNEMONICS[trimmed];
  if (direct) return direct.tip;

  const ciKey = Object.keys(CURATED_MNEMONICS).find(
    key => key.toLowerCase() === trimmed.toLowerCase(),
  );
  if (ciKey) return CURATED_MNEMONICS[ciKey].tip;

  if (examName && examName.trim()) {
    return `Exam Note: Tested in ${examName}. Key definition: ${
      enMeaning.trim() ? enMeaning : bnMeaning
    }.`;
  }
  return 'Revision Tip: Practice audio repetition 5–10 times to cement the Bengali & English meanings.';
}
